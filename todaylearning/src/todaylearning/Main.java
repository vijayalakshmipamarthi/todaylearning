package todaylearning;
import java.util.*;
public class Main {
	public static void main(String args[]) {
		Scanner sc= new Scanner(System.in);
		
		System.out.println("enter name");
		String name=sc.nextLine();
		System.out.println("name:" +name);
		
		System.out.println("enter age");
		int age=sc.nextInt();
		System.out.println("age:" +age);
		
		System.out.println("ener salary" );
		double salary =sc.nextDouble();
		System.out.println("salary:" +salary);
		
		System.out.println("enter fvalue:" );
		float fvalue =sc.nextFloat();
		System.out.println(" fvalue:"+fvalue );
		
		
		
		System.out.println("enter value" );
		short value  = sc.nextShort();
		System.out.println("value"+value );
		
		System.out.println("enter Lvalue" );
		long lvalue  = sc.nextLong();
		System.out.println("lvalue:" +lvalue);
		
		System.out.println("enter boolean value" );
		boolean bvalue=sc.nextBoolean();
		System.out.println("boolean value:" +  bvalue);
		
		
		
		
		
		
		
		
		
		
		
	}
	
}

		
		